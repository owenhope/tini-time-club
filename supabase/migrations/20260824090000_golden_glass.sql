-- Supabase projects that enable pg_cron get a daily refresh automatically.
-- Projects without it can invoke the same service-role function from their
-- deployment scheduler; keeping this optional makes local migrations portable.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
    BEGIN
      EXECUTE $job$
        SELECT cron.schedule(
          'golden-glass-daily-refresh',
          '15 8 * * *',
          'SELECT public.refresh_golden_glass_v1()'
        )
      $job$;
    EXCEPTION WHEN unique_violation THEN
      NULL;
    END;
  END IF;
END;
$$;

-- Recreate the legacy search RPCs before this migration commits. The view
-- rebuild above temporarily removes functions that return its row type, so
-- older clients must not observe a committed schema without search.
CREATE OR REPLACE FUNCTION public.search_locations(
  p_query text,
  p_limit integer DEFAULT 20
)
RETURNS SETOF public.location_ratings
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
  SELECT lr.*
  FROM public.location_ratings lr
  WHERE p_query IS NOT NULL
    AND length(trim(p_query)) >= 2
    AND (
      lr.name ILIKE '%' || trim(p_query) || '%'
      OR lr.address ILIKE '%' || trim(p_query) || '%'
      OR similarity(lr.name, trim(p_query)) > 0.25
    )
  ORDER BY
    (lr.name ILIKE '%' || trim(p_query) || '%') DESC,
    GREATEST(
      similarity(lr.name, trim(p_query)),
      similarity(COALESCE(lr.address, ''), trim(p_query))
    ) DESC,
    lr.total_ratings DESC,
    lr.id ASC
  LIMIT greatest(1, least(COALESCE(p_limit, 20), 50));
$$;

CREATE OR REPLACE FUNCTION public.search_locations(
  p_query text,
  p_limit integer,
  p_offset integer
)
RETURNS SETOF public.location_ratings
LANGUAGE sql
STABLE
SECURITY INVOKER
