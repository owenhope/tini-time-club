CREATE OR REPLACE FUNCTION public.is_golden_glass_location(p_location_id bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.golden_glass_snapshot snapshot
    JOIN public.regions region ON region.id = snapshot.region_id
    JOIN public.locations location ON location.id = snapshot.location_id
    WHERE snapshot.location_id = p_location_id
      AND region.enabled = true
      AND location.golden_glass_eligible = true
  );
$$;

