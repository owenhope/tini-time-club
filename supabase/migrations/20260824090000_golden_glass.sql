CREATE OR REPLACE FUNCTION public.get_region_members_v1(
  p_region_id bigint,
  p_search text DEFAULT NULL,
  p_limit integer DEFAULT 50
)
RETURNS TABLE (
  id uuid,
  username text,
  avatar_url text,
  is_verified boolean,
  follower_count integer,
  review_count bigint
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT p.id, p.username, p.avatar_url, p.is_verified,
    p.follower_count,
    count(r.id)::bigint AS review_count
  FROM public.profiles p
  JOIN public.reviews r ON r.user_id = p.id AND r.state = 1
  JOIN public.locations l ON l.id = r.location AND l.region_id = p_region_id
  JOIN public.regions region ON region.id = l.region_id AND region.enabled = true
  WHERE auth.uid() IS NOT NULL
    AND EXISTS (
      SELECT 1 FROM public.profiles viewer
      WHERE viewer.id = auth.uid() AND viewer.deleted = false
    )
    AND p.deleted = false
    AND p.username IS NOT NULL
    AND public.is_member_visible(p.id)
    AND (
      nullif(trim(p_search), '') IS NULL
      OR p.username ILIKE '%' || replace(replace(trim(p_search), '%', '\\%'), '_', '\\_') || '%'
    )
  GROUP BY p.id, p.username, p.avatar_url, p.is_verified, p.follower_count
  ORDER BY count(r.id) DESC, p.username, p.id
  LIMIT greatest(1, least(coalesce(p_limit, 50), 50));
$$;

