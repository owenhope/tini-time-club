-- Golden Glass is a current recognition projection, not an award history.
-- Regions and Google mappings are operator-owned; the client only receives
-- narrow, sanitized read interfaces.

BEGIN;

CREATE TABLE IF NOT EXISTS public.regions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  name text NOT NULL,
  enabled boolean NOT NULL DEFAULT true,
  display_order integer NOT NULL DEFAULT 0,
  center_lat double precision NOT NULL CHECK (center_lat BETWEEN -90 AND 90),
  center_lon double precision NOT NULL CHECK (center_lon BETWEEN -180 AND 180),
  viewport_ne_lat double precision NOT NULL CHECK (viewport_ne_lat BETWEEN -90 AND 90),
  viewport_ne_lon double precision NOT NULL CHECK (viewport_ne_lon BETWEEN -180 AND 180),
  viewport_sw_lat double precision NOT NULL CHECK (viewport_sw_lat BETWEEN -90 AND 90),
  viewport_sw_lon double precision NOT NULL CHECK (viewport_sw_lon BETWEEN -180 AND 180),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.region_google_places (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  region_id bigint NOT NULL REFERENCES public.regions(id) ON DELETE CASCADE,
  google_place_id text NOT NULL UNIQUE,
  google_label text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (region_id, google_place_id)
);

ALTER TABLE public.locations
  ADD COLUMN IF NOT EXISTS region_id bigint REFERENCES public.regions(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS neighborhood text,
  ADD COLUMN IF NOT EXISTS golden_glass_eligible boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS golden_glass_ineligibility_reason text;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.locations'::regclass
      AND conname = 'locations_golden_glass_eligibility_check'
  ) THEN
    ALTER TABLE public.locations
      ADD CONSTRAINT locations_golden_glass_eligibility_check
      CHECK (
        (golden_glass_eligible AND golden_glass_ineligibility_reason IS NULL)
        OR
        (NOT golden_glass_eligible
          AND nullif(trim(golden_glass_ineligibility_reason), '') IS NOT NULL)
      );
  END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS locations_region_idx
  ON public.locations (region_id, id);

CREATE TABLE IF NOT EXISTS public.golden_glass_snapshot (
  region_id bigint NOT NULL REFERENCES public.regions(id) ON DELETE CASCADE,
  location_id bigint NOT NULL REFERENCES public.locations(id) ON DELETE CASCADE,
  rank smallint NOT NULL CHECK (rank BETWEEN 1 AND 5),
  raw_overall numeric(3, 1) NOT NULL CHECK (raw_overall BETWEEN 1 AND 5),
  adjusted_score numeric(8, 5) NOT NULL,
  distinct_reviewers integer NOT NULL CHECK (distinct_reviewers >= 3),
  latest_review_at timestamptz NOT NULL,
  refreshed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (region_id, location_id),
  UNIQUE (region_id, rank)
);

CREATE INDEX IF NOT EXISTS golden_glass_snapshot_location_idx
  ON public.golden_glass_snapshot (location_id);

ALTER TABLE public.regions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.region_google_places ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.golden_glass_snapshot ENABLE ROW LEVEL SECURITY;

