-- Map reads carry only the existing aggregate fields plus the current status.
-- Region membership comes from locations.region_id, never from a viewport.
CREATE OR REPLACE FUNCTION public.locations_in_region_view(
  p_min_lat double precision,
  p_min_long double precision,
  p_max_lat double precision,
  p_max_long double precision,
  p_region_id bigint
)
RETURNS TABLE (
  id bigint,
  name text,
  address text,
  lat double precision,
  long double precision,
  rating double precision,
  taste_avg double precision,
  presentation_avg double precision,
  total_ratings integer,
  is_golden_glass boolean
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public, gis
AS $$
  SELECT l.id, l.name, l.address,
    gis.st_y(l.location::gis.geometry),
    gis.st_x(l.location::gis.geometry),
    round(avg((r.taste + r.presentation)::numeric / 2.0), 1)::double precision,
    round(avg(r.taste), 1)::double precision,
    round(avg(r.presentation), 1)::double precision,
    count(r.id)::integer,
    public.is_golden_glass_location(l.id)
  FROM public.locations l
  JOIN public.regions region ON region.id = l.region_id AND region.enabled = true
  JOIN public.reviews r ON r.location = l.id AND r.state = 1
  WHERE l.region_id = p_region_id
    AND gis.st_intersects(
      l.location,
      gis.st_makeenvelope(
        p_min_long, p_min_lat, p_max_long, p_max_lat, 4326
      )::gis.geography
    )
  GROUP BY l.id, l.name, l.address, l.location;
$$;

