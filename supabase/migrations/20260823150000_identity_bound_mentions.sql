  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (comment_id, start_offset)
);

-- This immutable ledger prevents remove/re-add edits from notifying the same
-- member more than once for one source. Notification rows may be withdrawn;
-- delivery history intentionally remains.
CREATE TABLE IF NOT EXISTS public.mention_delivery_ledger (
  source_kind text NOT NULL CHECK (source_kind IN ('review', 'comment')),
  source_id bigint NOT NULL,
  mentioned_profile_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  actor_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  notification_id uuid REFERENCES public.notifications(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (source_kind, source_id, mentioned_profile_id)
);

