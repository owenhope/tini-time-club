CREATE OR REPLACE FUNCTION public.update_review_v2(
  p_review_id bigint,
  p_image_url text,
  p_location_id bigint,
  p_spirit_id bigint,
  p_type_id bigint,
  p_taste numeric,
  p_presentation numeric,
  p_comment text,
  p_mentions jsonb DEFAULT '[]'::jsonb
) RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_actor_id uuid := auth.uid();
  v_review public.reviews;
  v_mentions jsonb;
BEGIN
  IF v_actor_id IS NULL OR char_length(COALESCE(p_comment, '')) > 500 THEN
    RAISE EXCEPTION 'The review update is invalid' USING ERRCODE = '22023';
  END IF;
  UPDATE public.reviews review
  SET image_url = p_image_url,
      location = p_location_id,
      spirit = p_spirit_id,
      type = p_type_id,
      taste = p_taste,
      presentation = p_presentation,
      comment = trim(COALESCE(p_comment, ''))
  WHERE review.id = p_review_id AND review.user_id = v_actor_id
  RETURNING * INTO v_review;

  IF v_review.id IS NULL THEN
    RAISE EXCEPTION 'The review is unavailable' USING ERRCODE = '42501';
  END IF;
  IF p_mentions IS NULL THEN
    -- The client could not load the existing spans; leave them untouched
    -- rather than treating the edit as a request to remove every mention.
    SELECT COALESCE(jsonb_agg(jsonb_build_object(
      'profileId', mention.mentioned_profile_id,
      'username', mention.username_snapshot,
      'start', mention.start_offset,
      'length', mention.token_length
    ) ORDER BY mention.start_offset), '[]'::jsonb)
    INTO v_mentions
    FROM public.review_mentions mention
    WHERE mention.review_id = v_review.id;
  ELSE
    v_mentions := public.replace_review_mentions_v1(
      v_review.id, v_review.comment, p_mentions
    );
  END IF;
  RETURN to_jsonb(v_review) || jsonb_build_object('mentions', v_mentions);
END;
$$;

