  FROM PUBLIC, anon, authenticated;

-- React Native selection offsets use JavaScript UTF-16 code units. Postgres
-- string positions use Unicode code points, so validate client offsets with a
-- small converter instead of accepting a matching token elsewhere in the
-- body. Usernames are ASCII, making token length identical in both systems.
CREATE OR REPLACE FUNCTION public.mention_token_matches_utf16(
  p_body text,
  p_start_offset integer,
  p_token text,
  p_token_length integer
) RETURNS boolean
LANGUAGE plpgsql
IMMUTABLE
STRICT
SET search_path = public, pg_temp
AS $$
DECLARE
  v_character text;
  v_character_index integer := 1;
  v_code_unit_offset integer := 0;
BEGIN
  IF p_start_offset < 0
     OR p_token_length <> char_length(p_token)
     OR p_token_length < 2 THEN
    RETURN false;
  END IF;

  WHILE v_character_index <= char_length(p_body)
        AND v_code_unit_offset < p_start_offset LOOP
    v_character := substring(p_body FROM v_character_index FOR 1);
    v_code_unit_offset := v_code_unit_offset + CASE
      WHEN octet_length(convert_to(v_character, 'UTF8')) = 4 THEN 2
      ELSE 1
    END;
    v_character_index := v_character_index + 1;
  END LOOP;

  -- The token must also end at a word boundary: '@bobs' is not a mention of
  -- '@bob', so a trailing username character rejects the span.
  RETURN v_code_unit_offset = p_start_offset
    AND substring(
      p_body FROM v_character_index FOR char_length(p_token)
    ) = p_token
    AND COALESCE(
      substring(p_body FROM v_character_index + char_length(p_token) FOR 1),
      ''
    ) !~ '^[A-Za-z0-9_]$';
END;
$$;

REVOKE ALL ON FUNCTION public.mention_token_matches_utf16(
  text, integer, text, integer
) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.enqueue_mention_once(
  p_source_kind text,
  p_source_id bigint,
  p_actor_id uuid,
  p_target_id uuid,
  p_review_id bigint,
  p_comment_id integer DEFAULT NULL
) RETURNS void
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_actor_name text;
  v_kind text;
  v_notification_id uuid;
  v_preference boolean;
BEGIN
  IF p_source_kind NOT IN ('review', 'comment')
     OR NOT public.mention_target_is_eligible(p_actor_id, p_target_id) THEN
    RETURN;
  END IF;

  -- Check the preference before writing delivery history: a ledger row for a
  -- muted mention would permanently block delivery after the member re-enables
  -- mention notifications.
  SELECT target.mention_notifications_enabled
  INTO v_preference
  FROM public.profiles target
  WHERE target.id = p_target_id;

  IF NOT COALESCE(v_preference, true) THEN RETURN; END IF;

  INSERT INTO public.mention_delivery_ledger (
    source_kind, source_id, mentioned_profile_id, actor_id
  ) VALUES (
    p_source_kind, p_source_id, p_target_id, p_actor_id
  ) ON CONFLICT DO NOTHING;

  IF NOT FOUND THEN
    -- Already delivered once. If a caption edit withdrew that notification,
    -- restore it instead of leaving the re-added mention invisible forever.
    DELETE FROM public.activity_withdrawals withdrawal
    USING public.notifications notification
    WHERE withdrawal.notification_id = notification.id
      AND withdrawal.reason = 'action_undone'
      AND notification.event_key = concat(
        'mention:', p_source_kind, ':', p_source_id, ':', p_target_id
      );
    RETURN;
  END IF;

  SELECT COALESCE(actor.username, 'Someone')
  INTO v_actor_name
  FROM public.profiles actor
  WHERE actor.id = p_actor_id;

  v_kind := CASE p_source_kind
    WHEN 'review' THEN 'mentioned_in_review'
    ELSE 'mentioned_in_comment'
  END;

  INSERT INTO public.notifications (
    user_id, actor_id, body, type, kind, data, event_key
  ) VALUES (
    p_target_id,
    p_actor_id,
    concat(
      v_actor_name,
      CASE p_source_kind
        WHEN 'review' THEN ' mentioned you in a review.'
        ELSE ' mentioned you in a comment.'
      END
    ),
    2,
    v_kind,
    jsonb_build_object(
      'kind', v_kind,
      'reviewId', p_review_id,
      'commentId', p_comment_id,
      'url', concat(
        '/r/', p_review_id,
        CASE WHEN p_comment_id IS NULL THEN ''
          ELSE concat('?comments=1&comment=', p_comment_id) END
      )
    ),
    concat('mention:', p_source_kind, ':', p_source_id, ':', p_target_id)
  ) ON CONFLICT (event_key) WHERE event_key IS NOT NULL DO NOTHING
  RETURNING id INTO v_notification_id;

  UPDATE public.mention_delivery_ledger
  SET notification_id = v_notification_id
  WHERE source_kind = p_source_kind
    AND source_id = p_source_id
    AND mentioned_profile_id = p_target_id;
END;
$$;

REVOKE ALL ON FUNCTION public.enqueue_mention_once(
  text, bigint, uuid, uuid, bigint, integer
) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.replace_review_mentions_v1(
  p_review_id bigint,
  p_body text,
  p_mentions jsonb DEFAULT '[]'::jsonb
) RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_actor_id uuid := auth.uid();
  v_item record;
  v_old_targets uuid[];
  v_result jsonb := '[]'::jsonb;
  v_target_id uuid;
  v_target_ids uuid[] := ARRAY[]::uuid[];
BEGIN
  IF v_actor_id IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.reviews r
    WHERE r.id = p_review_id AND r.user_id = v_actor_id
  ) THEN
    RAISE EXCEPTION 'The review is unavailable' USING ERRCODE = '42501';
  END IF;
  IF char_length(COALESCE(p_body, '')) > 500 THEN
    RAISE EXCEPTION 'Review captions are limited to 500 characters'
      USING ERRCODE = '22023';
  END IF;
  IF jsonb_typeof(COALESCE(p_mentions, '[]'::jsonb)) <> 'array'
     OR jsonb_array_length(COALESCE(p_mentions, '[]'::jsonb)) > 25 THEN
    RAISE EXCEPTION 'Mention payload is invalid' USING ERRCODE = '22023';
  END IF;

  SELECT COALESCE(array_agg(DISTINCT mentioned_profile_id)
    FILTER (WHERE mentioned_profile_id IS NOT NULL), ARRAY[]::uuid[])
  INTO v_old_targets
  FROM public.review_mentions
  WHERE review_id = p_review_id;

  DELETE FROM public.review_mentions WHERE review_id = p_review_id;

  FOR v_item IN
    SELECT * FROM jsonb_to_recordset(COALESCE(p_mentions, '[]'::jsonb))
      AS item(profile_id text, username text, start integer, length integer)
    ORDER BY start
  LOOP
    SELECT target.id INTO v_target_id
    FROM public.profiles target
    WHERE target.id::text = v_item.profile_id
      AND public.mention_target_is_eligible(v_actor_id, target.id)
      AND lower(target.username) = lower(v_item.username)
      AND v_item.username ~ '^[A-Za-z0-9_]{3,20}$'
      AND v_item.length = char_length(v_item.username) + 1
      AND public.mention_token_matches_utf16(
        p_body, v_item.start, '@' || v_item.username, v_item.length
      );

    IF v_target_id IS NULL THEN CONTINUE; END IF;
    IF NOT v_target_id = ANY(v_target_ids) THEN
      IF cardinality(v_target_ids) >= 5 THEN CONTINUE; END IF;
      v_target_ids := array_append(v_target_ids, v_target_id);
    END IF;

    BEGIN
      INSERT INTO public.review_mentions (
        review_id, mentioned_profile_id, username_snapshot,
        start_offset, token_length, created_by
      ) VALUES (
        p_review_id, v_target_id, v_item.username,
        v_item.start, v_item.length, v_actor_id
      );
      v_result := v_result || jsonb_build_array(jsonb_build_object(
        'profileId', v_target_id,
        'username', v_item.username,
        'start', v_item.start,
        'length', v_item.length
      ));
    EXCEPTION WHEN unique_violation OR check_violation THEN
      CONTINUE;
    END;
  END LOOP;

  FOREACH v_target_id IN ARRAY v_target_ids LOOP
    PERFORM public.enqueue_mention_once(
      'review', p_review_id, v_actor_id, v_target_id, p_review_id, NULL
    );
  END LOOP;

  FOREACH v_target_id IN ARRAY v_old_targets LOOP
    IF NOT v_target_id = ANY(v_target_ids) THEN
      INSERT INTO public.activity_withdrawals (notification_id, user_id, reason)
      SELECT notification.id, notification.user_id, 'action_undone'
      FROM public.notifications notification
      WHERE notification.event_key = concat(
        'mention:review:', p_review_id, ':', v_target_id
      )
      ON CONFLICT (notification_id) DO UPDATE
      SET reason = EXCLUDED.reason, withdrawn_at = now();
    END IF;
  END LOOP;

  RETURN v_result;
END;
$$;

REVOKE ALL ON FUNCTION public.replace_review_mentions_v1(bigint, text, jsonb)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.replace_review_mentions_v1(bigint, text, jsonb)
  TO authenticated, service_role;

